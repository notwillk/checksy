#!/usr/bin/env bash
set -euo pipefail

: "${RULESY_PROVISION_TRACE:?}"
: "${RULESY_PROVISION_FIXED:?}"
: "${RULESY_PROVISION_READY_FIFO:?}"
: "${RULESY_PROVISION_RELEASE_FIFO:?}"

printf 'ready\n' > "$RULESY_PROVISION_READY_FIFO"
IFS= read -r _ < "$RULESY_PROVISION_RELEASE_FIFO"
printf 'fix\n' >> "$RULESY_PROVISION_TRACE"
: > "$RULESY_PROVISION_FIXED"
